"""Generate the one local PCD operation; no network or Arr writes."""
import argparse
from pathlib import Path
from .evidence import pattern

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'ops' / '900000.cjk-chinese-subtitles.sql'
PROFILE = 'CJK 2160p Quality - Chinese Subs'
BASE = '2160p Quality'
MISSING = 'CJK - Missing Chinese Subtitle Evidence'
FORMATS = [('CJKSub', 'any', 1), ('CJKSubS', 'simplified', 2000),
           ('CJKSubT', 'traditional', 1), (MISSING, 'any', None)]

def quote(value):
    return "'" + str(value).replace("'", "''") + "'"

def generate():
    p, b = quote(PROFILE), quote(BASE)
    lines = [
        '-- @operation: custom', '-- @entity: batch',
        '-- @name: CJK Chinese subtitle evidence policy',
        '-- Generated by: python -m cjk.build_policy',
        '-- Reserve 900000+ for local operations, after upstream operations.',
        '-- Original upstream profiles are never modified.',
        "INSERT INTO tags (name) VALUES ('CJK Local');",
        f'''INSERT INTO quality_profiles
        (name, description, upgrades_allowed, minimum_custom_format_score,
         upgrade_until_score, upgrade_score_increment)
        SELECT {p}, 'Upstream 2160p Quality plus mandatory Chinese subtitle claims. Simplified preferred, Traditional and unspecified Chinese accepted. Use the CJK feed adapter for description evidence.',
        upgrades_allowed, minimum_custom_format_score, upgrade_until_score, upgrade_score_increment
        FROM quality_profiles WHERE name = {b};''',
        f"INSERT INTO quality_profile_tags VALUES ({p}, 'CJK Local');",
    ]
    for table, columns in [
        ('quality_groups', ['name']),
        ('quality_group_members', ['quality_group_name', 'quality_name', 'position']),
        ('quality_profile_qualities', ['quality_name', 'quality_group_name', 'position', 'enabled', 'upgrade_until']),
        ('quality_profile_languages', ['language_name', 'type']),
        ('quality_profile_custom_formats', ['custom_format_name', 'arr_type', 'score']),
    ]:
        cols = ', '.join(columns)
        lines.append(f'INSERT INTO {table} (quality_profile_name, {cols})\n'
                     f'SELECT {p}, {cols} FROM {table} WHERE quality_profile_name = {b};')
    for name, kind, score in FORMATS:
        n = quote(name)
        neg = int(score is None)
        desc = ('Rejects missing or contradictory Chinese subtitle evidence; penalty exceeds every positive score combined.'
                if neg else 'Explicit Chinese subtitle claim. Marker is retained by {Custom Formats} naming. Not an audio-language rule.')
        lines += [
            f'INSERT INTO regular_expressions (name, pattern, description) VALUES ({n}, {quote(pattern(kind))}, {quote(desc)});',
            f'INSERT INTO regular_expression_tags VALUES ({n}, \'CJK Local\');',
            f'INSERT INTO custom_formats (name, description, include_in_rename) VALUES ({n}, {quote(desc)}, {1-neg});',
            f'INSERT INTO custom_format_tags VALUES ({n}, \'CJK Local\');',
            f"INSERT INTO custom_format_conditions (custom_format_name, name, type, arr_type, negate, required) VALUES ({n}, 'Chinese subtitle evidence', 'release_title', 'all', {neg}, 1);",
            f"INSERT INTO condition_patterns VALUES ({n}, 'Chinese subtitle evidence', {n});",
        ]
        if score is not None:
            lines.append(f"INSERT INTO quality_profile_custom_formats VALUES ({p}, {n}, 'all', {score});")
        for title, kinds in [
            ('Example.S01E06.1080p.WEB-DL.CJKSubS-GROUP', {'any', 'simplified'}),
            ('Example.S01E06.1080p.WEB-DL.CJKSubT-GROUP', {'any', 'traditional'}),
            ('Example.2026.1080p.WEB-DL.CJKSubU-GROUP', {'any'}),
            ('Example.S01E06.1080p.WEB-DL.Mandarin-GROUP', set()),
            ('Example.S01E06.1080p.WEB-DL.CHS.CJKSubNO-GROUP', set()),
        ]:
            expected = int((kind in kinds) != bool(neg))
            for media in ('movie', 'series'):
                lines.append('INSERT INTO custom_format_tests (custom_format_name, title, type, should_match, description) '
                             f'VALUES ({n}, {quote(title)}, {quote(media)}, {expected}, \'Local evidence regression\');')
    for arr in ('radarr', 'sonarr'):
        lines.append(f'''-- Fail closed even if every positive upstream/custom bonus matches simultaneously.
INSERT INTO quality_profile_custom_formats
SELECT {p}, {quote(MISSING)}, '{arr}', -(COALESCE(SUM(CASE WHEN score > 0 THEN score ELSE 0 END), 0) + 1)
FROM quality_profile_custom_formats WHERE quality_profile_name = {p} AND arr_type IN ('all', '{arr}');''')
    lines.append("""INSERT INTO delay_profiles (name, preferred_protocol, usenet_delay, torrent_delay,
    bypass_if_highest_quality, bypass_if_above_custom_format_score, minimum_custom_format_score)
VALUES ('CJK Immediate', 'only_torrent', NULL, 0, 0, 0, NULL);""")
    return '\n\n'.join(lines) + '\n'

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding='utf-8') != content:
            raise SystemExit('Generated SQL is stale: run python -m cjk.build_policy')
        print('Generated SQL matches policy')
    else:
        OUTPUT.write_text(content, encoding='utf-8', newline='\n')
        print('Generated', OUTPUT.name)

if __name__ == '__main__':
    main()
